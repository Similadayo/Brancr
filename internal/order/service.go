// OrderService handles order creation and management
type OrderService struct {
	DB           *gorm.DB
	Logger       *zap.Logger
	AlertService interface {
		SendAlert(ctx context.Context, tenantID uuid.UUID, alertType, severity, title, message, actionURL, actionLabel string) (*storage.TenantAlert, error)
	}
}

// NewOrderService creates a new OrderService
func NewOrderService(db *gorm.DB, logger *zap.Logger) *OrderService {
	return &OrderService{
		DB:     db,
		Logger: logger,
	}
}

// SetAlertService sets the alert service
func (s *OrderService) SetAlertService(alertService interface {
	SendAlert(ctx context.Context, tenantID uuid.UUID, alertType, severity, title, message, actionURL, actionLabel string) (*storage.TenantAlert, error)
}) {
	s.AlertService = alertService
}

// CreateOrderFromSalesConversation creates an order when customer commits to purchase
func (s *OrderService) CreateOrderFromSalesConversation(
	ctx context.Context,
	tenantID uuid.UUID,
	customerID uuid.UUID,
	conversationID uuid.UUID,
	salesConv *storage.SalesConversation,
	customerName, customerPhone, customerEmail string,
	platform string,
) (*storage.Order, error) {
	// Check context cancellation
	select {
	case <-ctx.Done():
		return nil, ctx.Err()
	default:
	}

	// Check if order already exists for THIS SPECIFIC CONVERSATION
	// CRITICAL: Use conversationID for exact matching - NEVER guess based on "last order for customer"
	var existingOrder storage.Order
	if conversationID != uuid.Nil {
		// Look for ANY order for THIS SPECIFIC conversation (draft, pending, confirmed, paid)
		// This prevents creating duplicate orders when customer continues in same conversation
		// even if the order is already confirmed/paid.
		if err := s.DB.WithContext(ctx).
			Where("tenant_id = ? AND conversation_id = ?", tenantID, conversationID).
			Order("created_at DESC"). // Get most recent one for this conversation (should be only one usually)
			First(&existingOrder).Error; err == nil {

			// Order already exists for this conversation - return it
			s.Logger.Info("order already exists for this conversation, returning existing order",
				zap.Stringer("order_id", existingOrder.ID),
				zap.Stringer("conversation_id", conversationID),
				zap.String("status", existingOrder.Status),
				zap.Float64("amount", existingOrder.TotalAmount))
			return &existingOrder, nil
		}
	}

	// Extract items and calculate total
	items, totalAmount, err := s.ExtractOrderItems(salesConv)
	if err != nil {
		return nil, fmt.Errorf("failed to extract order items: %w", err)
	}

	if totalAmount <= 0 {
		return nil, fmt.Errorf("order total amount must be greater than 0")
	}

	// Generate order number
	orderNumber, err := s.GenerateOrderNumber(ctx, tenantID)
	if err != nil {
		return nil, fmt.Errorf("failed to generate order number: %w", err)
	}

	// Load tenant for name prefix
	var tenant storage.Tenant
	_ = s.DB.Preload("BusinessProfile").First(&tenant, tenantID).Error
	businessName := tenant.BusinessProfile.Name
	if businessName == "" {
		businessName = tenant.Name
	}

	itemLabel := ""
	if len(items) > 0 {
		itemLabel = items[0].Name
	}

	// Generate payment reference with retry on conflict
	// Note: There's a unique constraint on payment_reference, so we handle conflicts gracefully
	paymentReference := utils.GeneratePaymentReference(businessName, tenantID, itemLabel)
	maxRetries := 10
	for i := 0; i < maxRetries; i++ {
		// Check context cancellation
		select {
		case <-ctx.Done():
			return nil, ctx.Err()
		default:
		}

		var refExists storage.Order
		if err := s.DB.WithContext(ctx).Where("payment_reference = ?", paymentReference).First(&refExists).Error; err != nil {
			// Payment reference is unique, proceed
			break
		}
		// Conflict - generate new one
		paymentReference = utils.GeneratePaymentReference(businessName, tenantID, itemLabel)
		if i == maxRetries-1 {
			return nil, fmt.Errorf("failed to generate unique payment reference after %d retries", maxRetries)
		}
	}

	// Get payment instructions (will be generated by PaymentInstructionGenerator)
	// For now, we'll store empty and let it be populated when payment instructions are sent

	// Platform-specific customer identity defaults
	if customerName == "" || customerPhone == "" {
		var customer storage.Customer
		if err := s.DB.First(&customer, customerID).Error; err == nil {
			handle := customer.Username
			if handle == "" {
				handle = customer.PlatformID
			}

			name := customerName
			if name == "" {
				name = customer.DisplayName
			}
			if name == "" {
				name = customer.Username
			}
			if name == "" {
				name = fmt.Sprintf("Customer-%d", customer.ID)
			}

			phone := customerPhone
			switch strings.ToLower(platform) {
			case "whatsapp":
				if phone == "" {
					phone = customer.PlatformID
				}
			case "instagram", "facebook":
				phone = handle // store handle in phone field for visibility
			default:
				if phone == "" {
					phone = customer.PlatformID
				}
			}

			customerName = name
			customerPhone = phone
		}
	}

	// Create order
	itemsJSON, _ := json.Marshal(items)
	order := storage.Order{
		TenantID:         tenantID,
		CustomerID:       customerID,
		ConversationID:   conversationID, // CRITICAL: Explicit binding to conversation
		OrderNumber:      orderNumber,
		PaymentReference: paymentReference,
		Status:           "pending",
		TotalAmount:      totalAmount,
		Currency:         "NGN", // Default, can be made configurable
		Items:            string(itemsJSON),
		CustomerName:     customerName,
		CustomerPhone:    customerPhone,
		CustomerEmail:    customerEmail,
		Platform:         platform,
		DeliveryAddress:  salesConv.DeliveryAddress,
		IsPickup:         salesConv.PickupRequested,
		DeliveryNotes:    salesConv.PickupTime, // Use PickupTime as notes if pickup
		CreatedAt:        time.Now(),
	}

	// Create order with context and handle unique constraint violations
	if err := s.DB.WithContext(ctx).Create(&order).Error; err != nil {
		// Check if it's a unique constraint violation
		if strings.Contains(err.Error(), "duplicate") || strings.Contains(err.Error(), "unique") {
			s.Logger.Warn("order creation failed due to unique constraint violation",
				zap.String("payment_reference", paymentReference),
				zap.String("order_number", orderNumber),
				zap.Error(err))
			// Return existing order if possible
			var existingOrder storage.Order
			if err := s.DB.WithContext(ctx).Where("payment_reference = ? OR order_number = ?", paymentReference, orderNumber).
				First(&existingOrder).Error; err == nil {
				return &existingOrder, nil
			}
		}
		return nil, fmt.Errorf("failed to create order: %w", err)
	}

	s.Logger.Info("order created from sales conversation",
		zap.Stringer("order_id", order.ID),
		zap.String("order_number", order.OrderNumber),
		zap.String("payment_reference", order.PaymentReference),
		zap.Stringer("customer_id", customerID),
		zap.Float64("total_amount", totalAmount))

	// Send new order alert
	if s.AlertService != nil {
		title := fmt.Sprintf("New Order %s", order.OrderNumber)
		message := fmt.Sprintf("New order received from %s for %s%.2f", order.CustomerName, order.Currency, order.TotalAmount)
		actionURL := fmt.Sprintf("/app/orders/%s", order.ID)

		if _, err := s.AlertService.SendAlert(ctx, tenantID, "system", "info", title, message, actionURL, "View Order"); err != nil {
			s.Logger.Warn("failed to send new order alert", zap.Error(err), zap.Stringer("tenant_id", tenantID))
		}
	}

	return &order, nil
}

// ExtractOrderItems extracts items from sales conversation and calculates total
func (s *OrderService) ExtractOrderItems(salesConv *storage.SalesConversation) ([]storage.OrderItem, float64, error) {
	var items []storage.OrderItem
	var totalAmount float64

	// Parse items from sales conversation
	if salesConv.ItemsDiscussed != "" {
		var discussedItems []map[string]interface{}
		if err := json.Unmarshal([]byte(salesConv.ItemsDiscussed), &discussedItems); err != nil {
			return nil, 0, fmt.Errorf("failed to parse items discussed: %w", err)
		}

		for _, item := range discussedItems {
			name, _ := item["name"].(string)
			if name == "" {
				continue
			}

			// Extract price or lookup in DB if missing
			var price float64
			if p, ok := item["price"].(float64); ok {
				price = p
			} else if p, ok := item["price"].(int); ok {
				price = float64(p)
			}

			// Fallback: If price is 0, try to find product/menu item by name
			if price <= 0 {
				// Try Product
				var product storage.Product
				if err := s.DB.Where("LOWER(name) = ? AND tenant_id = ?", strings.ToLower(name), salesConv.TenantID).First(&product).Error; err == nil {
					price = product.Price
					s.Logger.Info("found price from product lookup", zap.String("item", name), zap.Float64("price", price))
				} else {
					// Try MenuItem
					var menuItem storage.MenuItem
					if err := s.DB.Where("LOWER(name) = ? AND tenant_id = ?", strings.ToLower(name), salesConv.TenantID).First(&menuItem).Error; err == nil {
						price = menuItem.Price
						s.Logger.Info("found price from menu item lookup", zap.String("item", name), zap.Float64("price", price))
					} else {
						// Try Service
						var service storage.Service
						if err := s.DB.Where("LOWER(name) = ? AND tenant_id = ?", strings.ToLower(name), salesConv.TenantID).First(&service).Error; err == nil {
							// Parse Pricing JSON
							// Format: {"type": "fixed", "amount": 50000} or {"type": "hourly", "rate": 5000}
							var pricing map[string]interface{}
							if err := json.Unmarshal([]byte(service.Pricing), &pricing); err == nil {
								if amt, ok := pricing["amount"].(float64); ok && amt > 0 {
									price = amt
								} else if rate, ok := pricing["rate"].(float64); ok && rate > 0 {
									price = rate
								}
							}

							// Fallback to max negotiation price if parsing failed but it exists
							if price <= 0 && service.NegotiationMaxPrice > 0 {
								price = service.NegotiationMaxPrice
							}

							if price > 0 {
								s.Logger.Info("found price from service lookup", zap.String("item", name), zap.Float64("price", price))
							}
						}
					}
				}
			}

			// No fallback - items without prices should be looked up from catalog, not use stale PriceDiscussed
			// This prevents the "7K order bug" where stale prices from previous conversations are used
			if price <= 0 {
				s.Logger.Warn("item price not found after DB lookup, skipping item", zap.String("item_name", name))
				continue
			}

			// Extract quantity (default to 1 if not specified)
			quantity := 1
			if q, ok := item["quantity"].(float64); ok {
				quantity = int(q)
			} else if q, ok := item["quantity"].(int); ok {
				quantity = q
			}

			description, _ := item["description"].(string)
			totalPrice := price * float64(quantity)

			orderItem := storage.OrderItem{
				Name:        name,
				Description: description,
				Quantity:    quantity,
				UnitPrice:   price,
				TotalPrice:  totalPrice,
			}

			items = append(items, orderItem)
			totalAmount += totalPrice
		}
	}

	// REMOVED: Fallback order creation from stale PriceDiscussed
	// This was causing the "7K order bug" where orders with no real items
	// were created using stale price values from previous conversations.
	// Orders should only be created when actual items are extracted.

	if len(items) == 0 {
		return nil, 0, fmt.Errorf("no items found in sales conversation - please specify what you want to order")
	}

	return items, totalAmount, nil
}

// GenerateOrderNumber generates a unique sequential order number
// Format: ORD-{YEAR}-{SEQUENTIAL}
func (s *OrderService) GenerateOrderNumber(ctx context.Context, tenantID uuid.UUID) (string, error) {
	year := time.Now().Year()

	// Get the last order number for this tenant this year
	var lastOrder storage.Order
	err := s.DB.Where("tenant_id = ?", tenantID).
		Where("order_number LIKE ?", fmt.Sprintf("ORD-%d-%%", year)).
		Order("created_at DESC").
		First(&lastOrder).Error

	sequenceNumber := 1
	if err == nil && lastOrder.OrderNumber != "" {
		// Extract sequence number from last order
		// Format: ORD-2024-001234
		var seq int
		if _, err := fmt.Sscanf(lastOrder.OrderNumber, fmt.Sprintf("ORD-%d-%%d", year), &seq); err == nil {
			sequenceNumber = seq + 1
		}
	}

	orderNumber := utils.GenerateOrderNumber(tenantID, sequenceNumber)

	// Ensure uniqueness (in case of race condition)
	var exists storage.Order
	for s.DB.Where("order_number = ?", orderNumber).First(&exists).Error == nil {
		sequenceNumber++
		orderNumber = utils.GenerateOrderNumber(tenantID, sequenceNumber)
	}

	return orderNumber, nil
}

// GetOrderByPaymentReference finds an order by payment reference
func (s *OrderService) GetOrderByPaymentReference(ctx context.Context, paymentReference string, tenantID uuid.UUID) (*storage.Order, error) {
	var order storage.Order
	if err := s.DB.Where("payment_reference = ? AND tenant_id = ?", paymentReference, tenantID).
		First(&order).Error; err != nil {
		return nil, err
	}
	return &order, nil
}

