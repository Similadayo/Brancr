// GetDraftOrderForConversation finds a draft order for a specific conversation
func (s *OrderService) GetDraftOrderForConversation(ctx context.Context, tenantID, conversationID uuid.UUID) (*storage.Order, error) {
	var order storage.Order
	if err := s.DB.WithContext(ctx).
		Where("tenant_id = ? AND conversation_id = ? AND status = ?", tenantID, conversationID, "draft").
		First(&order).Error; err != nil {
		return nil, err
	}
	return &order, nil
}

// CreateDraftOrder creates a DRAFT order when items+price+delivery are known
// Draft orders are safe, discardable, and don't require payment
// This is Phase 1 of the two-phase order lifecycle
func (s *OrderService) CreateDraftOrder(
	ctx context.Context,
	tenantID uuid.UUID,
	customerID uuid.UUID,
	conversationID uuid.UUID,
	salesConv *storage.SalesConversation,
	customerName, customerPhone, customerEmail string,
	platform string,
) (*storage.Order, error) {
	// Check if draft already exists for this conversation
	existing, err := s.GetDraftOrderForConversation(ctx, tenantID, conversationID)
	if err == nil && existing != nil {
		s.Logger.Info("draft order already exists for conversation, updating",
			zap.Stringer("order_id", existing.ID),
			zap.Stringer("conversation_id", conversationID))
		// Update the existing draft with latest items/price
		items, totalAmount, err := s.ExtractOrderItems(salesConv)
		if err == nil && totalAmount > 0 {
			itemsJSON, _ := json.Marshal(items)
			existing.Items = string(itemsJSON)
			existing.TotalAmount = totalAmount
			existing.DeliveryAddress = salesConv.DeliveryAddress
			existing.IsPickup = salesConv.PickupRequested
			s.DB.Save(existing)
		}
		return existing, nil
	}

	// Extract items and calculate total
	items, totalAmount, err := s.ExtractOrderItems(salesConv)
	if err != nil {
		return nil, fmt.Errorf("failed to extract order items: %w", err)
	}

	if totalAmount <= 0 {
		return nil, fmt.Errorf("cannot create draft order with zero total amount")
	}

	// Generate order number
	orderNumber, err := s.GenerateOrderNumber(ctx, tenantID)
	if err != nil {
		return nil, fmt.Errorf("failed to generate order number: %w", err)
	}

	// Generate payment reference
	var tenant storage.Tenant
	businessName := "Business"
	if err := s.DB.First(&tenant, tenantID).Error; err == nil {
		businessName = tenant.Name
	}

	itemLabel := ""
	if len(items) > 0 {
		itemLabel = items[0].Name
	}
	paymentReference := utils.GeneratePaymentReference(businessName, tenantID, itemLabel)

	// Platform-specific customer identity defaults
	if customerName == "" || customerPhone == "" {
		var customer storage.Customer
		if err := s.DB.First(&customer, customerID).Error; err == nil {
			if customerName == "" {
				customerName = customer.DisplayName
				if customerName == "" {
					customerName = customer.Username
				}
			}
			if customerPhone == "" {
				customerPhone = customer.PlatformID
			}
		}
	}

	// Create DRAFT order
	itemsJSON, _ := json.Marshal(items)
	order := storage.Order{
		TenantID:         tenantID,
		CustomerID:       customerID,
		ConversationID:   conversationID,
		OrderNumber:      orderNumber,
		PaymentReference: paymentReference,
		Status:           "draft", // CRITICAL: Draft status - safe, discardable
		TotalAmount:      totalAmount,
		Currency:         "NGN",
		Items:            string(itemsJSON),
		CustomerName:     customerName,
		CustomerPhone:    customerPhone,
		CustomerEmail:    customerEmail,
		Platform:         platform,
		DeliveryAddress:  salesConv.DeliveryAddress,
		IsPickup:         salesConv.PickupRequested,
		DeliveryNotes:    salesConv.PickupTime,
		CreatedAt:        time.Now(),
	}

	if err := s.DB.WithContext(ctx).Create(&order).Error; err != nil {
		return nil, fmt.Errorf("failed to create draft order: %w", err)
	}

	s.Logger.Info("📝 DRAFT order created (Phase 1)",
		zap.Stringer("order_id", order.ID),
		zap.Stringer("conversation_id", conversationID),
		zap.Float64("total_amount", totalAmount),
		zap.String("status", "draft"))

	return &order, nil
}

// PromoteDraftOrder promotes a draft order to pending (awaiting payment)
// This is Phase 2 of the two-phase order lifecycle
// Called when explicit payment intent is detected
func (s *OrderService) PromoteDraftOrder(ctx context.Context, orderID uuid.UUID) (*storage.Order, error) {
	var order storage.Order
	if err := s.DB.First(&order, orderID).Error; err != nil {
		return nil, fmt.Errorf("order not found: %w", err)
	}

	if order.Status != "draft" {
		return &order, nil // Already promoted or in different state
	}

	order.Status = "pending" // Now awaiting payment
	if err := s.DB.Save(&order).Error; err != nil {
		return nil, fmt.Errorf("failed to promote draft order: %w", err)
	}

	// Ensure a pending payment record exists for this order
	var existingPayment storage.Payment
	if err := s.DB.WithContext(ctx).
		Where("tenant_id = ? AND order_id = ?", order.TenantID, order.ID).
		First(&existingPayment).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			now := time.Now()
			payment := storage.Payment{
				TenantID:           order.TenantID,
				OrderID:            order.ID,
				CustomerID:         order.CustomerID,
				PaymentReference:   order.PaymentReference,
				Amount:             order.TotalAmount,
				Currency:           order.Currency,
				PaymentMethod:      "bank_transfer",
				Status:             "pending",
				VerificationStatus: "unverified",
				Metadata:           "{}",
				CreatedAt:          now,
			}
			if payment.Currency == "" {
				payment.Currency = "NGN"
			}

			maxRetries := 5
			for i := 0; i < maxRetries; i++ {
				if payment.PortalToken == "" {
					payment.PortalToken = utils.GeneratePortalToken()
				}
				if payment.ReceiptID == "" {
					payment.ReceiptID = utils.GenerateReceiptID()
				}
				if err := s.DB.WithContext(ctx).Create(&payment).Error; err != nil {
					if strings.Contains(err.Error(), "duplicate") || strings.Contains(err.Error(), "unique") {
						payment.PortalToken = ""
						payment.ReceiptID = ""
						continue
					}
					s.Logger.Warn("failed to create payment for promoted order", zap.Error(err), zap.Stringer("order_id", order.ID))
					break
				}
				break
			}
		} else {
			s.Logger.Warn("failed to check existing payment for promoted order", zap.Error(err), zap.Stringer("order_id", order.ID))
		}
	}

	s.Logger.Info("⬆️ Draft order PROMOTED to pending (Phase 2)",
		zap.Stringer("order_id", order.ID),
		zap.Float64("amount", order.TotalAmount))

	// Send new order alert (only on promotion, not on draft creation)
	if s.AlertService != nil {
		title := fmt.Sprintf("New Order %s", order.OrderNumber)
		message := fmt.Sprintf("New order from %s for %s%.2f", order.CustomerName, order.Currency, order.TotalAmount)
		actionURL := fmt.Sprintf("/app/orders/%s", order.ID)
		if _, err := s.AlertService.SendAlert(ctx, order.TenantID, "system", "info", title, message, actionURL, "View Order"); err != nil {
			s.Logger.Warn("failed to send new order alert", zap.Error(err))
		}
	}

	return &order, nil
}
