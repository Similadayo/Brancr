// OrderService handles order creation and management
type OrderService struct {
	DB     *gorm.DB
	Logger *zap.Logger
}

// NewOrderService creates a new OrderService
func NewOrderService(db *gorm.DB, logger *zap.Logger) *OrderService {
	return &OrderService{
		DB:     db,
		Logger: logger,
	}
}

// CreateOrderFromSalesConversation creates an order when customer commits to purchase
func (s *OrderService) CreateOrderFromSalesConversation(
	ctx context.Context,
	tenantID uint,
	customerID uint,
	conversationID uint,
	salesConv *storage.SalesConversation,
	customerName, customerPhone, customerEmail string,
	platform string,
) (*storage.Order, error) {
	// Check if order already exists for this conversation
	var existingOrder storage.Order
	if err := s.DB.Where("tenant_id = ? AND customer_id = ?", tenantID, customerID).
		Where("platform = ?", platform).
		Order("created_at DESC").
		First(&existingOrder).Error; err == nil {
		// Check if order was created recently (within last 5 minutes) for same conversation
		// This prevents duplicate orders from same commitment
		if time.Since(existingOrder.CreatedAt) < 5*time.Minute {
			s.Logger.Info("order already exists for recent commitment, returning existing order",
				zap.Uint("order_id", existingOrder.ID),
				zap.Uint("conversation_id", conversationID))
			return &existingOrder, nil
		}
	}

	// Extract items and calculate total
	items, totalAmount, err := s.ExtractOrderItems(salesConv)
	if err != nil {
		return nil, fmt.Errorf("failed to extract order items: %w", err)
	}

	if totalAmount <= 0 {
		return nil, fmt.Errorf("order total amount must be greater than 0")
	}

	// Generate order number
	orderNumber, err := s.GenerateOrderNumber(ctx, tenantID)
	if err != nil {
		return nil, fmt.Errorf("failed to generate order number: %w", err)
	}

	// Generate payment reference
	paymentReference := utils.GeneratePaymentReference(tenantID)

	// Ensure payment reference is unique
	var refExists storage.Order
	for s.DB.Where("payment_reference = ?", paymentReference).First(&refExists).Error == nil {
		paymentReference = utils.GeneratePaymentReference(tenantID)
	}

	// Get payment instructions (will be generated by PaymentInstructionGenerator)
	// For now, we'll store empty and let it be populated when payment instructions are sent

	// Create order
	itemsJSON, _ := json.Marshal(items)
	order := storage.Order{
		TenantID:         tenantID,
		CustomerID:       customerID,
		OrderNumber:      orderNumber,
		PaymentReference: paymentReference,
		Status:           "pending",
		TotalAmount:      totalAmount,
		Currency:         "NGN", // Default, can be made configurable
		Items:            string(itemsJSON),
		CustomerName:     customerName,
		CustomerPhone:    customerPhone,
		CustomerEmail:    customerEmail,
		Platform:         platform,
		CreatedAt:        time.Now(),
	}

	if err := s.DB.Create(&order).Error; err != nil {
		return nil, fmt.Errorf("failed to create order: %w", err)
	}

	s.Logger.Info("order created from sales conversation",
		zap.Uint("order_id", order.ID),
		zap.String("order_number", order.OrderNumber),
		zap.String("payment_reference", order.PaymentReference),
		zap.Uint("tenant_id", tenantID),
		zap.Uint("customer_id", customerID),
		zap.Float64("total_amount", totalAmount))

	return &order, nil
}

// ExtractOrderItems extracts items from sales conversation and calculates total
func (s *OrderService) ExtractOrderItems(salesConv *storage.SalesConversation) ([]storage.OrderItem, float64, error) {
	var items []storage.OrderItem
	var totalAmount float64

	// Parse items from sales conversation
	if salesConv.ItemsDiscussed != "" {
		var discussedItems []map[string]interface{}
		if err := json.Unmarshal([]byte(salesConv.ItemsDiscussed), &discussedItems); err != nil {
			return nil, 0, fmt.Errorf("failed to parse items discussed: %w", err)
		}

		for _, item := range discussedItems {
			name, _ := item["name"].(string)
			if name == "" {
				continue
			}

			// Extract price
			var price float64
			if p, ok := item["price"].(float64); ok {
				price = p
			} else if p, ok := item["price"].(int); ok {
				price = float64(p)
			} else {
				// Try to get from PriceDiscussed if item price not available
				if salesConv.PriceDiscussed > 0 && len(discussedItems) == 1 {
					price = salesConv.PriceDiscussed
				} else {
					s.Logger.Warn("item price not found, skipping item", zap.String("item_name", name))
					continue
				}
			}

			// Extract quantity (default to 1 if not specified)
			quantity := 1
			if q, ok := item["quantity"].(float64); ok {
				quantity = int(q)
			} else if q, ok := item["quantity"].(int); ok {
				quantity = q
			}

			description, _ := item["description"].(string)
			totalPrice := price * float64(quantity)

			orderItem := storage.OrderItem{
				Name:       name,
				Description: description,
				Quantity:   quantity,
				UnitPrice:  price,
				TotalPrice: totalPrice,
			}

			items = append(items, orderItem)
			totalAmount += totalPrice
		}
	}

	// If no items extracted but price discussed, create a single item
	if len(items) == 0 && salesConv.PriceDiscussed > 0 {
		item := storage.OrderItem{
			Name:       "Order",
			Quantity:   1,
			UnitPrice:  salesConv.PriceDiscussed,
			TotalPrice: salesConv.PriceDiscussed,
		}
		items = append(items, item)
		totalAmount = salesConv.PriceDiscussed
	}

	if len(items) == 0 {
		return nil, 0, fmt.Errorf("no items found in sales conversation")
	}

	return items, totalAmount, nil
}

// GenerateOrderNumber generates a unique sequential order number
// Format: ORD-{YEAR}-{SEQUENTIAL}
func (s *OrderService) GenerateOrderNumber(ctx context.Context, tenantID uint) (string, error) {
	year := time.Now().Year()

	// Get the last order number for this tenant this year
	var lastOrder storage.Order
	err := s.DB.Where("tenant_id = ?", tenantID).
		Where("order_number LIKE ?", fmt.Sprintf("ORD-%d-%%", year)).
		Order("created_at DESC").
		First(&lastOrder).Error

	sequenceNumber := 1
	if err == nil && lastOrder.OrderNumber != "" {
		// Extract sequence number from last order
		// Format: ORD-2024-001234
		var seq int
		if _, err := fmt.Sscanf(lastOrder.OrderNumber, fmt.Sprintf("ORD-%d-%%d", year), &seq); err == nil {
			sequenceNumber = seq + 1
		}
	}

	orderNumber := utils.GenerateOrderNumber(tenantID, sequenceNumber)

	// Ensure uniqueness (in case of race condition)
	var exists storage.Order
	for s.DB.Where("order_number = ?", orderNumber).First(&exists).Error == nil {
		sequenceNumber++
		orderNumber = utils.GenerateOrderNumber(tenantID, sequenceNumber)
	}

	return orderNumber, nil
}

// GetOrderByPaymentReference finds an order by payment reference
func (s *OrderService) GetOrderByPaymentReference(ctx context.Context, paymentReference string, tenantID uint) (*storage.Order, error) {
	var order storage.Order
	if err := s.DB.Where("payment_reference = ? AND tenant_id = ?", paymentReference, tenantID).
		First(&order).Error; err != nil {
		return nil, err
	}
	return &order, nil
}

// GetOrderByConversationID finds an order by conversation ID
func (s *OrderService) GetOrderByConversationID(ctx context.Context, conversationID uint, tenantID uint) (*storage.Order, error) {
	// Orders don't directly have conversation_id, but we can find via customer and recent orders
	// This is a simplified lookup - in production, you might want to add conversation_id to Order model
	var order storage.Order
	if err := s.DB.Where("tenant_id = ?", tenantID).
		Order("created_at DESC").
		First(&order).Error; err != nil {
		return nil, err
	}
	return &order, nil
}

